// Generates icons/icon{16,48,128}.png (a #0a0a0a rounded square with a lime "P1") and
// src/generated/icon.ts (the 128px PNG as a data: URI for the Wallet Standard `icon`).
// Pure Node: a minimal PNG encoder on top of node:zlib. No canvas, no dependencies.
import { deflateSync } from 'node:zlib';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// ── PNG encoder ──
const CRC_TABLE = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function u32(n) {
  const b = Buffer.alloc(4);
  b.writeUInt32BE(n >>> 0);
  return b;
}
function chunk(type, data) {
  const t = Buffer.from(type, 'ascii');
  return Buffer.concat([u32(data.length), t, data, u32(crc32(Buffer.concat([t, data])))]);
}
function encodePNG(width, height, rgba) {
  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (width * 4 + 1)] = 0; // filter: none
    rgba.copy(raw, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4);
  }
  const ihdr = Buffer.concat([u32(width), u32(height), Buffer.from([8, 6, 0, 0, 0])]);
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

// ── artwork ──
const BG = [0x0a, 0x0a, 0x0a];
const LIME = [0x8a, 0xd4, 0x14];
const P = ['1111.', '1...1', '1...1', '1111.', '1....', '1....', '1....'];
const ONE = ['..1..', '.11..', '..1..', '..1..', '..1..', '..1..', '.111.'];
const GLYPH = P.map((row, i) => row + '.' + ONE[i]); // 11 x 7 cells

function draw(size) {
  const px = Buffer.alloc(size * size * 4);
  const radius = Math.max(2, Math.round(size * 0.2));
  const inside = (x, y) => {
    // rounded-rect test against the corner circles
    const cx = x < radius ? radius : x >= size - radius ? size - radius - 1 : x;
    const cy = y < radius ? radius : y >= size - radius ? size - radius - 1 : y;
    const dx = x - cx;
    const dy = y - cy;
    return dx * dx + dy * dy <= radius * radius;
  };
  const cell = Math.max(1, Math.floor((size * 0.74) / 11));
  const gw = 11 * cell;
  const gh = 7 * cell;
  const ox = Math.floor((size - gw) / 2);
  const oy = Math.floor((size - gh) / 2);
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const i = (y * size + x) * 4;
      if (!inside(x, y)) continue; // transparent corner
      let col = BG;
      const gx = Math.floor((x - ox) / cell);
      const gy = Math.floor((y - oy) / cell);
      if (x >= ox && y >= oy && gx < 11 && gy < 7 && GLYPH[gy][gx] === '1') col = LIME;
      px[i] = col[0];
      px[i + 1] = col[1];
      px[i + 2] = col[2];
      px[i + 3] = 255;
    }
  }
  return encodePNG(size, size, px);
}

const outDir = join(root, 'public', 'icons');
mkdirSync(outDir, { recursive: true });
let png128;
for (const size of [16, 48, 128]) {
  const png = draw(size);
  if (size === 128) png128 = png;
  writeFileSync(join(outDir, `icon${size}.png`), png);
}

const genDir = join(root, 'src', 'generated');
mkdirSync(genDir, { recursive: true });
writeFileSync(
  join(genDir, 'icon.ts'),
  `// Generated by scripts/make-icons.mjs — do not edit.\nexport const ICON_DATA_URI = 'data:image/png;base64,${png128.toString('base64')}' as const;\n`,
);
console.log(`icons: wrote public/icons/icon{16,48,128}.png and src/generated/icon.ts (${png128.length} bytes @128)`);
