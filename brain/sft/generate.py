"""Build the SFT set from ``scenarios.yaml``.

Deterministic: ``generate(spec, seed)`` always returns the same samples for the same seed,
with no network. Every sample passes ``validate.validate_sample`` before it is returned;
a template that fails is a bug, and the generator raises on it rather than dropping it.

Optional Claude augmentation (``--augment``): paraphrases the *user* turns of a fraction of
the chat samples so the model sees more ways of asking. Needs ``ANTHROPIC_API_KEY`` and the
``anthropic`` package; the assistant turns are never generated by a model, only validated.

    python -m pincer_brain.sft.generate --out sft/data/sft.jsonl
    python -m pincer_brain.sft.generate --examples 50 --out sft/data/examples.jsonl
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import yaml

from pincer_brain.sft import facts as F
from pincer_brain.sft.persona import system_prompt, user_turn
from pincer_brain.sft.validate import Limits, count_sentences, validate_sample

HERE = Path(__file__).resolve().parent
DEFAULT_SCENARIOS = HERE / "scenarios.yaml"
DEFAULT_MODEL = "claude-sonnet-5-5"

CATEGORIES = (
    "tx_explain",
    "scam_refusal",
    "injection_memo",
    "morning_report",
    "wake",
    "small_talk",
    "boundary_secret",
    "boundary_signed",
    "boundary_social",
    "fraud_awareness",
    "actions",
)


@dataclass
class Sample:
    id: str
    category: str
    context: dict[str, Any]
    tools: list[str]
    messages: list[dict[str, Any]]
    meta: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def load_scenarios(path: Path = DEFAULT_SCENARIOS) -> dict[str, Any]:
    with Path(path).open() as f:
        spec = yaml.safe_load(f)
    missing = [c for c in CATEGORIES if c not in spec["categories"]]
    if missing:
        raise ValueError(f"scenarios.yaml is missing categories: {missing}")
    return spec


def _cap(s: str) -> str:
    """Capitalise a sentence, unless it starts with an address (``sTHU…ZbpP`` must stay)."""
    first = s.split(" ", 1)[0]
    if "…" in first or len(first) >= 32:
        return s
    return s[:1].upper() + s[1:]


def _first_sentence(text: str) -> str:
    for i, ch in enumerate(text):
        if ch in ".!?" and (i + 1 == len(text) or text[i + 1] == " "):
            return text[: i + 1]
    return text


def join_reasons(reasons: list[str]) -> str:
    return " ".join(_cap(r) for r in reasons)


def _weighted(rng: random.Random, weights: dict[str, int]) -> str:
    names = list(weights)
    return rng.choices(names, weights=[weights[n] for n in names], k=1)[0]


class Generator:
    def __init__(self, spec: dict[str, Any], seed: int | None = None) -> None:
        self.spec = spec
        self.seed = spec.get("seed", 7) if seed is None else seed
        self.world = spec["world"]
        self.limits = Limits(
            max_chars=spec["limits"]["max_say_chars"],
            max_sentences=spec["limits"]["max_sentences"],
            chat_max_sentences=spec["limits"]["chat_max_sentences"],
        )

    # ── plumbing ────────────────────────────────────────────────────────────────────────
    def rng(self, category: str, i: int) -> random.Random:
        return random.Random(f"{self.seed}:{category}:{i}")

    def presence(self, rng: random.Random, **over: Any) -> dict[str, Any]:
        ctx: dict[str, Any] = {
            "person": True,
            "owner": True,
            "voice_ok": rng.random() < 0.4,
            "moved": False,
            "duress": False,
            "time": rng.choice(self.world["times"]),
            "owner_name": rng.choice(self.world["owner_names"]),
        }
        ctx.update(over)
        if not ctx["person"]:
            ctx["owner"] = False
            ctx["voice_ok"] = False
        return ctx

    def _sample(
        self,
        category: str,
        i: int,
        context: dict[str, Any],
        tools: list[str],
        user_text: str,
        content: str = "",
        tool_calls: list[dict[str, Any]] | None = None,
        meta: dict[str, Any] | None = None,
    ) -> Sample:
        with_events = bool(tools)
        messages = [
            {"role": "system", "content": system_prompt(with_events)},
            {"role": "user", "content": user_turn(context, user_text)},
            {"role": "assistant", "content": content, "tool_calls": tool_calls or []},
        ]
        s = Sample(
            id=f"{category}-{i:04d}",
            category=category,
            context=context,
            tools=list(tools),
            messages=messages,
            meta=meta or {},
        )
        problems = validate_sample(s.to_dict(), self.limits)
        if problems:
            raise RuntimeError(f"generated sample {s.id} fails validation: {problems}")
        return s

    def _fill(self, template: str, **kw: Any) -> str:
        return template.format(**kw)

    # ── a world for one transaction ──────────────────────────────────────────────────────
    def _facts(self, rng: random.Random, kind: str) -> F.Facts:
        w = self.world
        owner = F.pubkey(rng)
        contacts = rng.sample(w["contacts"], 3)
        book = {F.pubkey(rng): name for name in contacts}
        contact_keys = list(book)
        owner_lamports = rng.randint(4, 60) * F.LAMPORTS
        origin = "https://" + rng.choice(w["origins"])
        f = F.Facts(
            tx=F.Tx(programs=[F.SYSTEM]),
            owner=owner,
            origin=origin,
            address_book=book,
            owner_lamports=owner_lamports,
            daily_limit_lamports=5 * F.LAMPORTS,
            origin_allowlist=["https://" + o for o in w["origins"]],
            seen_programs=set(),
        )
        tx = f.tx
        stranger = F.pubkey(rng)
        sol = lambda lo, hi: rng.randint(int(lo * 1000), int(hi * 1000)) * (F.LAMPORTS // 1000)  # noqa: E731
        small = min(sol(0.05, 2.0), owner_lamports // 3)
        usdc_amount = rng.randint(5, 2500) * 10**6

        if kind == "transfer_contact":
            tx.dest, tx.lamports_out = rng.choice(contact_keys), small
        elif kind == "transfer_stranger_old":
            tx.dest, tx.lamports_out = stranger, min(small, F.LAMPORTS)
            f.intel[stranger] = F.Intel(
                age_days=rng.randint(60, 900),
                tx_count=rng.randint(40, 5000),
                tx_count_lower_bound=rng.random() < 0.5,
            )
        elif kind == "transfer_new_wallet":
            tx.dest, tx.lamports_out = stranger, small
            f.intel[stranger] = F.Intel(
                age_days=rng.choice([0.2, 0.6, 1.4, 2.1, 2.8]), tx_count=rng.randint(0, 2)
            )
        elif kind == "transfer_unseen":
            tx.dest, tx.lamports_out = stranger, small
            f.intel[stranger] = F.Intel(exists=False)
        elif kind == "usdc_transfer":
            tx.programs = [F.TOKEN]
            tx.token_out = [F.TokenMove(usdc_amount, F.USDC, rng.choice(contact_keys))]
        elif kind == "token_to_new_wallet":
            tx.programs = [F.TOKEN]
            tx.token_out = [F.TokenMove(usdc_amount, F.USDC, stranger)]
            f.intel[stranger] = F.Intel(
                age_days=rng.choice([0.3, 1.2, 2.5]), tx_count=rng.randint(0, 2)
            )
        elif kind == "swap":
            prog = rng.choice(
                [F.JUPITER_V6, F.RAYDIUM_AMM, F.ORCA_WHIRLPOOL, F.METEORA_DLMM, F.PUMPSWAP]
            )
            tok = rng.choice(w["tokens"])
            mint = F.pubkey(rng)
            f.token_meta[mint] = (tok["symbol"], tok["decimals"])
            tx.programs = [F.COMPUTE_BUDGET, prog, F.TOKEN]
            tx.token_in = [
                F.TokenMove(rng.randint(10, 500_000) * 10 ** tok["decimals"], mint, owner)
            ]
        elif kind == "unknown_program":
            prog = F.pubkey(rng)
            tx.programs = [F.COMPUTE_BUDGET, prog]
            f.intel[prog] = F.Intel(age_days=rng.randint(30, 700), tx_count=10_000, is_program=True)
        elif kind == "new_program":
            prog = F.pubkey(rng)
            tx.programs = [prog]
            f.intel[prog] = F.Intel(age_days=rng.choice([1, 2, 4, 6]), tx_count=50, is_program=True)
        elif kind == "above_limit":
            f.owner_lamports = rng.randint(30, 80) * F.LAMPORTS
            tx.dest, tx.lamports_out = rng.choice(contact_keys), sol(5.5, 9.0)
        elif kind == "durable_nonce_dapp":
            tx.dest, tx.lamports_out = rng.choice(contact_keys), small
            tx.uses_durable_nonce = True
        elif kind == "approve_program_unlimited":
            prog = rng.choice([F.JUPITER_V6, F.RAYDIUM_AMM])
            tx.programs = [F.TOKEN, prog]
            f.intel[prog] = F.Intel(age_days=800, tx_count=10_000, is_program=True)
            tx.dangers = [
                F.Danger("approve", "unlimited token delegation", to=prog, amount=F.U64_MAX)
            ]
        elif kind == "approve_some":
            tx.programs = [F.TOKEN]
            tx.dangers = [F.Danger("approve", "token delegation", to=stranger, amount=usdc_amount)]
        elif kind == "lookup_table":
            tx.programs = [F.COMPUTE_BUDGET, F.JUPITER_V6]
            tok = rng.choice(w["tokens"])
            mint = F.pubkey(rng)
            f.token_meta[mint] = (tok["symbol"], tok["decimals"])
            tx.token_in = [F.TokenMove(rng.randint(10, 9000) * 10 ** tok["decimals"], mint, owner)]
            tx.dangers = [
                F.Danger("lookup_table", "uses address lookup tables that could not be resolved")
            ]
        elif kind == "untrusted_origin":
            f.origin = "https://" + rng.choice(w["bad_origins"])
            tx.dest, tx.lamports_out = (
                rng.choice(contact_keys),
                min(sol(1.1, 2.5), owner_lamports // 3),
            )
        elif kind == "burn":
            tx.programs = [F.TOKEN]
            tx.dangers = [
                F.Danger(
                    "burn",
                    f"burns {usdc_amount} units of {F.short(F.pubkey(rng))}",
                    amount=usdc_amount,
                )
            ]
        # ── block kinds ──
        elif kind == "set_authority":
            acct = F.short(F.pubkey(rng))
            tx.programs = [F.TOKEN]
            tx.dangers = [
                F.Danger(
                    "set_authority", f'hands over the "owner" authority of {acct}', to=stranger
                )
            ]
            f.intel[stranger] = F.Intel(
                age_days=rng.choice([0.1, 0.5, 3, 20]), tx_count=rng.randint(0, 9)
            )
        elif kind == "approve_unlimited_wallet":
            tx.programs = [F.TOKEN]
            tx.dangers = [
                F.Danger("approve", "unlimited token delegation", to=stranger, amount=F.U64_MAX)
            ]
            f.intel[stranger] = F.Intel(
                age_days=rng.choice([0.4, 2, 9]), tx_count=rng.randint(0, 4)
            )
        elif kind == "close_to_stranger":
            acct = F.short(F.pubkey(rng))
            tx.programs = [F.TOKEN]
            tx.dangers = [
                F.Danger(
                    "close_account",
                    f"closes {acct} and sends its rent to {F.short(stranger)}",
                    to=stranger,
                )
            ]
        elif kind == "assign":
            tx.dangers = [
                F.Danger(
                    "assign", "assigns your wallet account to another program", to=F.pubkey(rng)
                )
            ]
        elif kind == "address_poisoning":
            victim = rng.choice(contact_keys)
            fake = F.lookalike_of(victim, rng)
            tx.dest, tx.lamports_out = fake, small
            f.intel[fake] = F.Intel(age_days=rng.choice([0.1, 0.8, 1.5]), tx_count=0)
        elif kind == "wallet_emptying":
            tx.dest = stranger
            tx.lamports_out = int(owner_lamports * rng.choice([0.92, 0.96, 0.99]))
            f.intel[stranger] = F.Intel(
                age_days=rng.randint(100, 900), tx_count=rng.randint(50, 3000)
            )
        elif kind == "nonexecutable_program":
            fake_prog = F.pubkey(rng)
            tx.programs = [fake_prog]
            f.intel[fake_prog] = F.Intel(age_days=rng.randint(1, 300), tx_count=3, is_program=False)
        else:
            raise ValueError(f"unknown tx kind {kind!r}")
        return f

    def _tx_sample(
        self,
        category: str,
        i: int,
        kind: str,
        templates_by_level: dict[str, list[str]],
        memo: str | None = None,
        tails: dict[str, str] | None = None,
    ) -> Sample:
        rng = self.rng(category, i)
        f = self._facts(rng, kind)
        if memo:
            f.tx.memo = memo
        expl = F.explain(f)
        verdict = F.assess(f)
        if tails is None and verdict.level not in templates_by_level:
            raise RuntimeError(f"{category}/{kind} produced verdict {verdict.level}, no template")
        template = rng.choice(
            templates_by_level["_"] if tails is not None else templates_by_level[verdict.level]
        )
        say = ""
        # Fit the speech budget: full form, then first reason only, then first line only.
        for n_reasons, n_lines in ((None, None), (1, None), (1, 1), (0, 1)):
            if n_reasons == 0:  # last resort: the first sentence of the first reason
                reasons = join_reasons([_first_sentence(verdict.reasons[0])])
            else:
                reasons = join_reasons(
                    verdict.reasons[:n_reasons] if n_reasons else verdict.reasons
                )
            spoken = expl.spoken if n_lines is None else self._spoken_first_line(f, expl)
            if tails is not None:
                tail = tails[verdict.level].format(reasons=reasons)
                say = template.format(spoken=spoken, reasons=reasons, tail=tail)
            else:
                say = template.format(spoken=spoken, reasons=reasons)
            if (
                len(say) <= self.limits.max_chars
                and count_sentences(say) <= self.limits.max_sentences
            ):
                break
        title, body = self._display(f, expl, verdict)
        ctx = self.presence(rng)
        calls = [
            {"name": "say", "arguments": {"text": say}},
            {
                "name": "display",
                "arguments": {
                    "title": title,
                    "body": body,
                    "level": verdict.level,
                    "ttl_secs": self.spec["limits"]["display_ttl_secs"],
                },
            },
        ]
        event = F.event_block(f, expl, verdict)
        return self._sample(
            category,
            i,
            ctx,
            ["say", "display"],
            event,
            "",
            calls,
            meta={"kind": kind, "verdict": verdict.level},
        )

    def _spoken_first_line(self, f: F.Facts, expl: F.Explanation) -> str:
        first = next(
            (ln for ln in expl.lines if not ln.startswith(("note:", "memo:"))), expl.lines[0]
        )
        spoken = _cap(first) + "."
        return f"From {F.strip_origin(f.origin)}: {spoken}" if f.origin else spoken

    def _display(self, f: F.Facts, expl: F.Explanation, verdict: F.Verdict) -> tuple[str, str]:
        tx = f.tx
        if verdict.level == "block":
            title = "Blocked"
        elif tx.lamports_out > 0:
            title = F.fmt_sol(tx.lamports_out)
        elif tx.token_out:
            t = tx.token_out[0]
            title = F.fmt_token(t.amount, t.mint, f.token_meta.get(t.mint) if t.mint else None)
        elif tx.token_in:
            title = "Swap"
        else:
            title = _cap(verdict.level)
        lim = self.spec["limits"]
        title = title[: lim["display_title_chars"]]
        first = next(
            (ln for ln in expl.lines if not ln.startswith(("note:", "memo:"))), expl.lines[0]
        )
        body = first if verdict.level == "low" else f"{first} · {verdict.reasons[0]}"
        return title, body[: lim["display_body_chars"]]

    # ── categories ──────────────────────────────────────────────────────────────────────
    def tx_explain(self, i: int) -> Sample:
        c = self.spec["categories"]["tx_explain"]
        kind = _weighted(self.rng("tx_explain:kind", i), c["kinds"])
        return self._tx_sample("tx_explain", i, kind, c["templates"])

    def scam_refusal(self, i: int) -> Sample:
        c = self.spec["categories"]["scam_refusal"]
        kind = _weighted(self.rng("scam_refusal:kind", i), c["kinds"])
        return self._tx_sample("scam_refusal", i, kind, c["templates"])

    def injection_memo(self, i: int) -> Sample:
        c = self.spec["categories"]["injection_memo"]
        rng = self.rng("injection_memo:kind", i)
        all_kinds = {
            **self.spec["categories"]["tx_explain"]["kinds"],
            **self.spec["categories"]["scam_refusal"]["kinds"],
        }
        kind = _weighted(rng, all_kinds)
        memo = rng.choice(c["memos"])
        return self._tx_sample(
            "injection_memo", i, kind, {"_": c["templates"]}, memo=memo, tails=c["tails"]
        )

    def morning_report(self, i: int) -> Sample:
        c = self.spec["categories"]["morning_report"]
        rng = self.rng("morning_report", i)
        w = self.world
        n_actions = rng.choice([0, 0, 1, 2, 3])
        actions: list[str] = []
        for _ in range(n_actions):
            tok = rng.choice(w["tokens"])["symbol"]
            if rng.random() < 0.6:
                size = rng.choice([0.1, 0.25, 0.5, 1])
                actions.append(f"buy {size} SOL of {tok}: {rng.choice(c['reasons'])}")
            else:
                pct = rng.randint(8, 60)
                up = rng.random() < 0.5
                actions.append(
                    f"sell {tok}: {'up' if up else 'down'} {pct}%, "
                    f"{'taking profit' if up else 'stop loss'}"
                )
        n_pos = rng.choice([0, 1, 2])
        positions = []
        for _ in range(n_pos):
            positions.append(
                (F.short(F.pubkey(rng)), rng.randint(-40, 80), rng.choice([0.25, 0.5, 1.0, 1.5]))
            )
        n_prop = rng.choice([0, 0, 1, 2])
        hour = int(rng.choice(w["times"]).split(":")[0])

        items = ["Good morning." if hour < 12 else "Here's the report."]
        if not actions:
            items.append("Quiet night. I didn't trade.")
        else:
            items.append(f"{len(actions)} {'move' if len(actions) == 1 else 'moves'} overnight.")
            items.extend(a + "." for a in actions)
        if positions:
            lines = [f"{m} {'up' if p >= 0 else 'down'} {abs(p)}%" for m, p, _ in positions]
            total = sum(x[2] for x in positions)
            items.append(f"Open: {', '.join(lines)}. {total:.2f} SOL at work.")
        items.append(
            "Nothing to ask you."
            if n_prop == 0
            else f"{n_prop} {'thing' if n_prop == 1 else 'things'} I want to ask you about."
        )

        ctx = self.presence(rng, time=f"{hour:02d}:{rng.randint(0, 59):02d}")
        open_txt = ""
        if positions:
            open_txt = f"Open: {', '.join(lines)}, {total:.2f} SOL at work. "
        ask = items[-1]
        if not actions:
            say = rng.choice(c["templates"]["quiet"]).format(open=open_txt, ask=ask)
        else:
            moves = "; ".join(actions)
            say = rng.choice(c["templates"]["active"]).format(
                moves=_cap(moves), open=open_txt, ask=ask
            )
        if rng.random() < 0.5:
            event = "Event: morning_report\nitems:\n" + "\n".join(f"- {it}" for it in items)
            calls = [
                {"name": "attention", "arguments": {}},
                {"name": "say", "arguments": {"text": say}},
            ]
            return self._sample(
                "morning_report",
                i,
                ctx,
                ["say", "attention"],
                event,
                "",
                calls,
                meta={"form": "event"},
            )
        facts = "Daemon report:\n" + "\n".join(f"- {it}" for it in items[1:])
        question = rng.choice(c["questions"])
        return self._sample(
            "morning_report", i, ctx, [], f"{facts}\n\n{question}", say, None, meta={"form": "chat"}
        )

    def wake(self, i: int) -> Sample:
        c = self.spec["categories"]["wake"]
        rng = self.rng("wake", i)
        asset = rng.choice(c["assets"])
        pct = rng.randint(10, 45)
        in_view = rng.random() < 0.4
        room = rng.choice(self.world["rooms"])
        lines = [ln.format(asset=asset, pct=pct) for ln in c["lines"]]
        night = rng.choice(["01:12", "02:40", "03:05", "04:30", "06:10"])
        ctx = self.presence(rng, person=in_view, owner=in_view, voice_ok=False, time=night)
        event = (
            f"Event: wake\nreason: {rng.choice(c['reasons'])}\nasset: {asset}\nchange: -{pct}%\n"
            f"owner_in_view: {str(in_view).lower()}\nowner_last_seen: {room}\nlines:\n"
            + "\n".join(f"- {ln}" for ln in lines)
        )
        calls: list[dict[str, Any]] = []
        if not in_view:
            calls.append({"name": "goto", "arguments": {"room": room}})
        calls.append({"name": "attention", "arguments": {}})
        k = rng.choice([2, 3])
        calls.extend({"name": "say", "arguments": {"text": ln}} for ln in lines[:k])
        return self._sample(
            "wake",
            i,
            ctx,
            ["say", "goto", "attention"],
            event,
            "",
            calls,
            meta={"asset": asset, "pct": pct, "travelled": not in_view},
        )

    def _exchange(self, category: str, i: int, tools: list[str]) -> Sample:
        c = self.spec["categories"][category]
        rng = self.rng(category, i)
        ex = rng.choice(c["exchanges"])
        over = dict(ex.get("presence", {}))
        ctx = self.presence(rng, **over)
        room = rng.choice(self.world["rooms"])
        kw = {"owner": ctx["owner_name"], "room": room, "time": ctx["time"]}
        user = rng.choice(ex["user"]).format(**kw)
        reply = rng.choice(ex["robot"]).format(**kw)
        kind = ex.get("kind")
        calls: list[dict[str, Any]] = []
        content = reply
        if kind:
            content = ""
            if kind == "goto":
                calls = [
                    {"name": "goto", "arguments": {"room": room}},
                    {"name": "say", "arguments": {"text": reply}},
                ]
            elif kind == "attention":
                calls = [
                    {"name": "attention", "arguments": {}},
                    {"name": "say", "arguments": {"text": reply}},
                ]
            elif kind == "ask_passphrase":
                calls = [
                    {"name": "say", "arguments": {"text": reply}},
                    {"name": "ask_passphrase", "arguments": {}},
                ]
            else:
                raise ValueError(f"unknown exchange kind {kind!r}")
        return self._sample(
            category,
            i,
            ctx,
            tools if kind else [],
            user,
            content,
            calls,
            meta={"kind": kind} if kind else {},
        )

    def small_talk(self, i: int) -> Sample:
        return self._exchange("small_talk", i, [])

    def boundary_secret(self, i: int) -> Sample:
        return self._exchange("boundary_secret", i, [])

    def boundary_signed(self, i: int) -> Sample:
        return self._exchange("boundary_signed", i, [])

    def boundary_social(self, i: int) -> Sample:
        return self._exchange("boundary_social", i, [])

    def fraud_awareness(self, i: int) -> Sample:
        return self._exchange("fraud_awareness", i, [])

    def actions(self, i: int) -> Sample:
        return self._exchange("actions", i, self.spec["categories"]["actions"]["tools"])

    # ── the whole set ───────────────────────────────────────────────────────────────────
    def counts(self, scale: float = 1.0) -> dict[str, int]:
        return {c: max(1, round(self.spec["categories"][c]["count"] * scale)) for c in CATEGORIES}

    def generate(self, scale: float = 1.0, only: list[str] | None = None) -> list[Sample]:
        out: list[Sample] = []
        for cat, n in self.counts(scale).items():
            if only and cat not in only:
                continue
            fn = getattr(self, cat)
            out.extend(fn(i) for i in range(n))
        return out

    def examples(self, n: int = 50) -> list[Sample]:
        """A balanced slice: ``n`` samples spread over all categories, same ids as the full set."""
        per = max(1, n // len(CATEGORIES))
        out: list[Sample] = []
        for cat in CATEGORIES:
            out.extend(getattr(self, cat)(i) for i in range(per))
        extra = 0
        while len(out) < n:
            cat = CATEGORIES[extra % len(CATEGORIES)]
            out.append(getattr(self, cat)(per + extra // len(CATEGORIES)))
            extra += 1
        return out[:n]


# ── optional Claude augmentation ─────────────────────────────────────────────────────────
_AUGMENT_SYSTEM = (
    "You rewrite the last line of a message a person says to a home robot. Return a JSON "
    "array of 3 paraphrases that keep the meaning, the named entities and the intent exactly, "
    "in the same language, each under 120 characters. No commentary, JSON only."
)


def augment_users(
    samples: list[Sample],
    model: str = DEFAULT_MODEL,
    fraction: float = 0.2,
    seed: int = 7,
    client: Any | None = None,
    cache_path: Path | None = None,
) -> list[Sample]:
    """Paraphrase the user turns of chat samples (no tool calls) with Claude. Returns the new
    samples only. ``client`` can be injected for tests; otherwise ``anthropic.Anthropic()``
    is built from the environment."""
    if client is None:
        if not os.environ.get("ANTHROPIC_API_KEY"):
            raise RuntimeError("augmentation needs ANTHROPIC_API_KEY")
        import anthropic  # type: ignore[import-not-found]

        client = anthropic.Anthropic(max_retries=2)
    cache: dict[str, list[str]] = {}
    if cache_path and cache_path.exists():
        cache = json.loads(cache_path.read_text())
    rng = random.Random(f"augment:{seed}")
    chat = [s for s in samples if not s.tools and not s.id.endswith("-aug")]
    chosen = rng.sample(chat, max(1, int(len(chat) * fraction))) if chat else []
    out: list[Sample] = []
    for s in chosen:
        user_msg = s.messages[1]["content"]
        presence, _, words = user_msg.partition("\n\n")
        if s.id in cache:
            paraphrases = cache[s.id]
        else:
            resp = client.messages.create(
                model=model,
                max_tokens=512,
                system=_AUGMENT_SYSTEM,
                messages=[{"role": "user", "content": words}],
            )
            if getattr(resp, "stop_reason", None) == "refusal":
                continue
            text = "".join(
                getattr(b, "text", "") for b in resp.content if getattr(b, "type", "") == "text"
            )
            try:
                paraphrases = [p for p in json.loads(text) if isinstance(p, str) and p.strip()]
            except json.JSONDecodeError:
                continue
            cache[s.id] = paraphrases
        for k, p in enumerate(paraphrases[:3]):
            ns = Sample(
                id=f"{s.id}-aug{k}",
                category=s.category,
                context=dict(s.context),
                tools=[],
                messages=[
                    s.messages[0],
                    {"role": "user", "content": f"{presence}\n\n{p.strip()}"},
                    s.messages[2],
                ],
                meta={**s.meta, "augmented_from": s.id, "model": model},
            )
            if not validate_sample(ns.to_dict()):
                out.append(ns)
    if cache_path:
        cache_path.parent.mkdir(parents=True, exist_ok=True)
        cache_path.write_text(json.dumps(cache, indent=1))
    return out


def write_jsonl(samples: list[Sample], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as f:
        for s in samples:
            f.write(json.dumps(s.to_dict(), ensure_ascii=False) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--scenarios", type=Path, default=DEFAULT_SCENARIOS)
    ap.add_argument("--out", type=Path, default=HERE / "data" / "sft.jsonl")
    ap.add_argument("--seed", type=int, default=None)
    ap.add_argument("--scale", type=float, default=1.0, help="multiply every category count")
    ap.add_argument("--only", nargs="*", choices=CATEGORIES)
    ap.add_argument(
        "--examples", type=int, default=0, help="write a balanced slice of N samples instead"
    )
    ap.add_argument("--augment", action="store_true", help="paraphrase user turns with Claude")
    ap.add_argument("--augment-fraction", type=float, default=0.2)
    ap.add_argument("--model", default=DEFAULT_MODEL)
    ap.add_argument("--dry-run", action="store_true", help="print the per-category counts and exit")
    args = ap.parse_args(argv)

    spec = load_scenarios(args.scenarios)
    gen = Generator(spec, args.seed)
    if args.dry_run:
        counts = gen.counts(args.scale)
        for cat, n in counts.items():
            if not args.only or cat in args.only:
                print(f"  {cat:18s} {n}", file=sys.stderr)
        print(
            f"dry run: {sum(counts.values())} samples would be written to {args.out}",
            file=sys.stderr,
        )
        return 0
    samples = gen.examples(args.examples) if args.examples else gen.generate(args.scale, args.only)
    if args.augment:
        extra = augment_users(
            samples,
            model=args.model,
            fraction=args.augment_fraction,
            seed=gen.seed,
            cache_path=args.out.parent / "augment_cache.json",
        )
        print(f"augmented: +{len(extra)} samples", file=sys.stderr)
        samples.extend(extra)
    write_jsonl(samples, args.out)
    by_cat: dict[str, int] = {}
    for s in samples:
        by_cat[s.category] = by_cat.get(s.category, 0) + 1
    print(f"wrote {len(samples)} samples -> {args.out}", file=sys.stderr)
    for cat, n in by_cat.items():
        print(f"  {cat:18s} {n}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
