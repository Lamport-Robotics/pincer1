#!/usr/bin/env python3
"""Provision one Pincer1 beacon: device id, LoRa shared key, Find My master seed.

Writes them to a `.env`-style file (default beacon/beacon.env, gitignored) and prints the build
and flash commands. The build reads the file through tools/keyflags.py and bakes the values into
the firmware as -D flags.

  python3 tools/provision.py --region AS923          # Thailand
  python3 tools/provision.py --region EU868 --out /secure/beacon-2.env

Then, from beacon/:

  pio run -e tbeam-supreme -t upload                 # the beacon
  pio run -e base-heltec   -t upload                 # the base station
  python3 tools/findmy_keys.py --env beacon.env > findmy_keys.json   # for the Find My fetcher

What the secrets protect, honestly: the LoRa key authenticates arm/disarm/ping and hides the
position from anyone else with a LoRa receiver; the Find My seed is what lets you (and only you)
decrypt the location reports Apple returns. Both are baked into the beacon's flash and are
readable by anyone who opens the robot and dumps the ESP32 (flash encryption is not enabled in
v1). That is accepted: the beacon reveals where the robot is, never a key that moves funds, and a
thief who has already found and dumped the beacon has the robot anyway. Keep the .env file off the
robot and out of git; it is the only copy of the Find My seed, and the seed is the only way to
read the reports.
"""
from __future__ import annotations

import argparse
import os
import secrets
import stat
import sys
from datetime import datetime, timezone

REGIONS = ("EU868", "US915", "AS923")


def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    beacon_dir = os.path.dirname(here)
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--region", choices=REGIONS, default="EU868", help="LoRa region (AS923 for Thailand)")
    ap.add_argument("--out", default=os.path.join(beacon_dir, "beacon.env"), help="where to write the env file")
    ap.add_argument("--force", action="store_true", help="overwrite an existing file (the old seed is then lost)")
    args = ap.parse_args()

    if os.path.exists(args.out) and not args.force:
        print(f"error: {args.out} exists; pass --force to replace it (the old Find My seed will be lost)", file=sys.stderr)
        return 2

    device_id = secrets.token_bytes(8)
    lora_key = secrets.token_bytes(32)
    findmy_seed = secrets.token_bytes(32)

    body = "\n".join([
        "# Pincer1 beacon provisioning. Generated by tools/provision.py on "
        + datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC") + ".",
        "# Keep this file out of git (beacon/.gitignore covers beacon.env and *.env). It is the only",
        "# copy of the Find My seed; without it the location reports cannot be read.",
        f"BEACON_DEVICE_ID={device_id.hex()}",
        f"BEACON_LORA_KEY={lora_key.hex()}",
        f"BEACON_FINDMY_SEED={findmy_seed.hex()}",
        f"BEACON_REGION={args.region}",
        "# optional: 1 = heartbeats carry a coarse (0.01 degree) position; 0 = heartbeats carry no position",
        "BEACON_HEARTBEAT_POSITION=1",
        "",
    ])
    fd = os.open(args.out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, stat.S_IRUSR | stat.S_IWUSR)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(body)

    print(f"wrote {args.out} (mode 0600)")
    print(f"  device id   {device_id.hex()}")
    print(f"  region      {args.region}")
    print("  LoRa key and Find My seed: in the file only")
    print()
    print("Build and flash (from beacon/; the build picks the file up through tools/keyflags.py):")
    env_note = "" if os.path.abspath(args.out) == os.path.join(beacon_dir, "beacon.env") else f"BEACON_ENV={args.out} "
    print(f"  {env_note}pio run -e tbeam-supreme -t upload     # beacon, T-Beam Supreme")
    print(f"  {env_note}pio run -e tbeam-v12 -t upload         # beacon, older T-Beam v1.2")
    print(f"  {env_note}pio run -e base-heltec -t upload       # base station")
    print()
    print("Equivalent explicit flags, if you prefer not to keep the file next to the project:")
    print(
        "  PLATFORMIO_BUILD_FLAGS='"
        f"-DBEACON_DEVICE_ID_HEX=\\\"{device_id.hex()}\\\" "
        f"-DBEACON_LORA_KEY_HEX=\\\"{lora_key.hex()}\\\" "
        f"-DBEACON_FINDMY_SEED_HEX=\\\"{findmy_seed.hex()}\\\" "
        f"-DBEACON_REGION_{args.region}=1' pio run -e tbeam-supreme -t upload"
    )
    print()
    print("Find My key list for the fetcher (OpenHaystack / macless-haystack / FindMy.py):")
    print(f"  python3 tools/findmy_keys.py --env {args.out} --count 2000 > findmy_keys.json")
    print()
    print("Reminder: the keys are readable by anyone with physical access to the beacon's flash.")
    print("They reveal the robot's location, not funds. See README 'Security'.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
